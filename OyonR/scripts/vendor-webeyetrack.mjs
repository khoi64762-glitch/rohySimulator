import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const upstreamEntry = require.resolve('webeyetrack');
const upstreamBundle = readFileSync(upstreamEntry, 'utf8');
const expectedBundleHash = '11075aa7e0abf971ecbba41dbca935f39d283b2d4b9169070d2d33eb94f79c18';
const actualBundleHash = createHash('sha256').update(upstreamBundle).digest('hex');

if (actualBundleHash !== expectedBundleHash) {
  throw new Error(
    `webeyetrack@0.0.2 bundle changed: expected ${expectedBundleHash}, got ${actualBundleHash}`,
  );
}

const upstreamLicense = readFileSync(`${upstreamEntry}.LICENSE.txt`, 'utf8');
const outputDir = resolve(root, 'vendor');
const output = `// Generated by scripts/vendor-webeyetrack.mjs from webeyetrack@0.0.2.\n` +
  `// The embedded upstream bundle SHA-256 is ${expectedBundleHash}.\n` +
  `const module = { exports: {} };\n` +
  `const exports = module.exports;\n` +
  `${upstreamBundle}\n` +
  `const bundledWebEyeTrack = module.exports;\n` +
  `export const WebEyeTrack = bundledWebEyeTrack.WebEyeTrack;\n` +
  `export const WebEyeTrackProxy = bundledWebEyeTrack.WebEyeTrackProxy;\n` +
  `export const WebcamClient = bundledWebEyeTrack.WebcamClient;\n` +
  `export const FaceLandmarkerClient = bundledWebEyeTrack.FaceLandmarkerClient;\n` +
  `export const BlazeGaze = bundledWebEyeTrack.BlazeGaze;\n` +
  `export default bundledWebEyeTrack;\n`;

mkdirSync(outputDir, { recursive: true });
writeFileSync(resolve(outputDir, 'webeyetrack.js'), output);
writeFileSync(resolve(outputDir, 'webeyetrack.LICENSE.txt'), upstreamLicense);

// Lifecycle hooks must leave stdout available for machine-readable npm output
// such as `npm pack --json`.
console.error(`vendor-webeyetrack: embedded reviewed bundle ${actualBundleHash}`);
